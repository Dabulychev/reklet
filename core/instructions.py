def render_page_instruction(key: str) -> None:
    item = INSTRUCTIONS.get(key)
    if not item:
        return
    title, text = item
    st.markdown("---")
    with st.expander("Инструкция", expanded=False):
        st.markdown(f"**{title}**")
        st.write(text)
